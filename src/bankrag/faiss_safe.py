"""Единственное место импорта FAISS, модуль нужно импортировать раньше scikit-learn.

На macOS у FAISS и torch разные копии OpenMP, и процесс падает с ошибкой сегментации,
если FAISS загружен раньше torch или работает в несколько потоков. Поэтому число потоков
задаётся до загрузки библиотек, а torch загружается первым. Индекс строится дольше,
зато запрос и так однопоточный. LightGBM с этим модулем не сочетается, он работает
в отдельных процессах.

Две копии OpenMP в процессе остаются, и без KMP_DUPLICATE_LIB_OK среда выполнения
остановит программу. Этот флаг считается небезопасным при многопоточной работе, поэтому
он допустим только вместе с одним потоком. scikit-learn при импорте выставляет его сам.
"""
from __future__ import annotations

import os

os.environ["OMP_NUM_THREADS"] = "1"
os.environ["KMP_DUPLICATE_LIB_OK"] = "TRUE"

import torch  # noqa: E402, F401
import faiss  # noqa: E402

__all__ = ["faiss"]
